"""The WHDLoad slave of a build: SWOS.slave with its base patch table.

The slave is assembled twice (whdload/build.py): first with a zero base
table of the final size (its symbols give the table's jump targets and the
slave block template), then with the real table, which must leave every
symbol where it was. The CRC-32 values of SWOS2, SWOS2.REL and the editor
file and the SWOS2 identity are assembled in (slave_gen.i).
"""
from __future__ import annotations

import importlib.util
import struct
from pathlib import Path

import manifest as patch_manifest
from buildlib import BuildError, Executable, REPO, check_cap, crc32, write_json, SWOS2_RUNTIME_SHA256
import buildlib

DATA = Path(__file__).resolve().parent / "whdload"
# A model slave base, used to check the patched image; WHDLoad loads the
# slave at an address only known at run time.
MODEL_SLAVE_BASE = 0x40010000


def whdload_module():
    """whdload/build.py, the slave builder."""
    spec = importlib.util.spec_from_file_location("whdload_build", REPO / "whdload/build.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def table_size(patches: list[patch_manifest.Patch]) -> int:
    """Bytes of the table the patches give (manifest.table_bytes layout)."""
    size = 2
    for patch in patches:
        spec = patch.replacement
        fixups = len(spec["fixups"]) if "template" in spec else 0 if "binary" in spec else 1
        size += 12 + 2 * fixups + patch.length + (patch.length & 1)
    return size


def slave_include(exe: Executable, image: bytes) -> str:
    identity = bytes.fromhex(SWOS2_RUNTIME_SHA256)[:8]
    return "\n".join([
        "; Generated by tools/build/slave_build.py. Do not edit.",
        f"SWOS2_REL_SIZE equ {len(exe.rel)}",
        f"SWOS2_RAW_CRC32 equ ${crc32(exe.raw):08X}",
        f"SWOS2_REL_CRC32 equ ${crc32(exe.rel):08X}",
        f"SWOS2_RUNTIME_CRC32 equ ${crc32(exe.runtime):08X}",
        f"EDITOR_FILE_LENGTH equ {len(image)}",
        f"EDITOR_FILE_CRC32 equ ${crc32(image):08X}",
        "SWOS2_IDENTITY macro",
        "        dc.b    " + ",".join(f"${byte:02X}" for byte in identity),
        "        endm", ""])


def build_slave(exe: Executable, caps: dict, out: Path, image: bytes) -> dict:
    whdload = whdload_module()
    gen = out / "slave-gen"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "slave_gen.i").write_text(slave_include(exe, image))
    patches = patch_manifest.load_manifest(DATA / "base_manifest.json")
    if any(patch.table != "base" for patch in patches):
        raise BuildError("the base manifest may only hold base patches")
    size = table_size(patches)
    (gen / "base_table.bin").write_bytes(bytes(size))
    tools = {"vasm": buildlib.VASM, "vlink": buildlib.VLINK}
    try:
        first, symbols = whdload.position_independent(gen, out / "obj" / "slave-pass1", **tools)
        resolved = patch_manifest.resolve(patches, exe, images={"slave": symbols},
                                          image_bytes={"slave": first}, base=caps["SWOS2_BASE"])
        table = patch_manifest.table_bytes(resolved)
        patch_manifest.decode_table(table)
        if len(table) != size:
            raise BuildError(f"base table has {len(table)} bytes, {size} were reserved")
        (gen / "base_table.bin").write_bytes(table)
        code, final_symbols = whdload.position_independent(gen, out / "obj" / "slave-pass2", **tools)
        slave = whdload.hunk_executable(code)
        if whdload.hunk_code(slave)[:len(code)] != code:
            raise BuildError("the slave hunk does not hold the linked code")
    except whdload.SlaveError as exc:
        raise BuildError(str(exc)) from exc
    if final_symbols != symbols:
        raise BuildError("inserting the base table moved symbols of the slave")
    offset = symbols["base_table"]
    if code[offset:offset + len(table)] != table or symbols["base_table_end"] != offset + len(table):
        raise BuildError("the base table is not where the slave expects it")
    check_cap("slave", len(code), caps["SLAVE_MAX_SIZE"])
    patched = patch_manifest.apply_runtime(exe.runtime, resolved, image_base=MODEL_SLAVE_BASE,
                                           base=caps["SWOS2_BASE"])
    block = caps["SLAVE_BLOCK"] - caps["SWOS2_BASE"]
    if patched[block + caps["SB_MAGIC"]:block + caps["SB_MAGIC"] + 4] != b"SWHD" or \
            struct.unpack_from(">I", patched, block + caps["SB_SLAVE"])[0] != MODEL_SLAVE_BASE:
        raise BuildError("the base table does not put the slave block in place")
    (out / "base_table.bin").write_bytes(table)
    (out / "base_table.i").write_text(patch_manifest.table_include(resolved, "base"))
    write_json(out / "slave_symbols.json", dict(sorted(symbols.items())))
    return {"slave": slave, "code": code, "symbols": symbols, "resolved": resolved, "table": table,
            "icon": whdload.icon(whdload.SLAVE_NAME), "names": (whdload.SLAVE_NAME, whdload.ICON_NAME,
                                                                  whdload.EDITOR_NAME, whdload.SAVE_DIRECTORY)}
