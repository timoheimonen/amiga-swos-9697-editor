# Native pages that get editor entries: name, template symbol, entry count,
# restore callback (replaced or kept) and the navigation bytes the editor
# writes, as (native entry, direction).
DIRECTIONS = ("LEFT", "RIGHT", "UP", "DOWN")
# Entries named under actions get their action operand offset exported, so
# the editor can point those actions of its copy at its own wrappers.
TEAM_NAME_ROWS = range(39, 55)
EXTENDED_PAGES = {
    "MAIN_MENU": ("main_menu_template", 14, [(1, "UP")], []),
    "TEAM_EDITOR": ("team_editor_template", 61,
                    [(20, "DOWN"), (21, "DOWN"), (22, "DOWN")]
                    + [(entry, "LEFT") for entry in (5, 6, 7, 9, 10, 11)]
                    + [(entry, "RIGHT") for entry in TEAM_NAME_ROWS], [20, 21]),
    "DIY_TYPE": ("diy_type_template", 5, [(3, "DOWN"), (4, "UP")], []),
    "DIY_LEAGUE": ("diy_league_template", 24, [(21, "LEFT"), (21, "RIGHT")], [20, 21]),
    "DIY_CUP": ("diy_cup_template", 52, [(49, "LEFT"), (49, "RIGHT")], [48, 49]),
    "DIY_TOURNAMENT": ("diy_tournament_template", 93, [(89, "DOWN"), (90, "DOWN"), (91, "DOWN")],
                       [89, 90]),
}
# Pages that are only measured, without editor entries (none at present).
MEASURED_PAGES: dict[str, str] = {}


def editor_constants(exe: Executable, caps: dict, gen: Path) -> dict:
    """Measure the native templates the editor copies and extends."""
    base = caps["SWOS2_BASE"]
    values, pages = {}, {}
    for page, (symbol, count, patches, actions) in EXTENDED_PAGES.items():
        template = caps[symbol]
        menu = decode(exe.runtime, template)
        start = template - base
        if len(menu["entries"]) != count:
            raise BuildError(f"{symbol} has {len(menu['entries'])} entries, expected {count}")
        if exe.runtime[menu["source_end"] - 2:menu["source_end"]] != b"\xfc\x19":
            raise BuildError(f"{symbol} does not end with $FC19")
        prefix = exe.runtime[start:menu["source_end"] - 2]
        values[f"{page}_PREFIX_SIZE"] = len(prefix)
        values[f"{page}_PREFIX_CRC32"] = crc32(prefix)
        values[f"{page}_ENTRIES"] = count
        offsets = {}
        for entry, direction in patches:
            source = menu["entries"][entry]["navigation_source"]
            if source is None:
                raise BuildError(f"{symbol} entry {entry} has no navigation bytes")
            offset = source - start + DIRECTIONS.index(direction)
            values[f"{page}_NAV_{entry}_{direction}"] = offset
            offsets[(entry, direction)] = offset
        for entry in actions:
            info = menu["entries"][entry]
            source = info["action_source"]
            if source is None or not info["source_start"] <= source < info["source_end"]:
                raise BuildError(f"{symbol} entry {entry} has no action operand of its own")
            values[f"{page}_ACTION_{entry}"] = source - start
        pages[page] = {"symbol": symbol, "prefix": prefix, "menu": menu, "offsets": offsets}
    if caps["main_menu_restore_noop"] != pages["MAIN_MENU"]["menu"]["restore"]:
        raise BuildError("native main-menu restore callback differs from the reference release")
    # The SWOS2 identity every database manifest carries.
    identity = bytes.fromhex(SWOS2_SHA256)
    for index in range(8):
        values[f"SWOS2_ID_{index}"] = int.from_bytes(identity[4 * index:4 * index + 4], "big")
    write_include(gen / "editor_gen.i", [f"{key} equ ${value:X}" for key, value in values.items()])
    return {"values": values, "pages": pages}


def link_editor(out: Path, gen: Path, shift: Path, caps: dict, variant: Variant = RELEASE) -> dict:
    objects, shifted = [], []
    sources = EDITOR_SOURCES + tuple(variant.sources)
    defines = variant.defines
    for source in sources:
        name = source.stem
        objects.append(assemble(source, out / "obj" / f"{name}.o", include=[gen],
                                listing=out / "obj" / f"{name}.lst", defines=defines))
        shifted.append(assemble(source, out / "obj" / f"{name}-shifted.o", include=[gen],
                                include_first=[shift], defines=defines))
    low_map = link(objects, out / "obj" / "editor-low.bin", 0)
    link(objects, out / "obj" / "editor-high.bin", FIXUP_PROBE_DELTA)
    link(shifted, out / "obj" / "editor-shifted.bin", 0)
    low = (out / "obj" / "editor-low.bin").read_bytes()
    high = (out / "obj" / "editor-high.bin").read_bytes()
    moved = (out / "obj" / "editor-shifted.bin").read_bytes()
    fixups = infer_fixups(low, high, limit=caps["EDITOR_AREA_SIZE"])
    imports = infer_imports(low, moved, caps["SWOS2_BASE"], caps["SWOS2_IMAGE_END"])
    if set(fixups) & set(imports):
        raise BuildError("a field is both relocated and imported")
    return {"code": low, "map": low_map, "fixups": fixups, "imports": imports}


def compose_image(linked: dict, hook_table: bytes, caps: dict,
                  variant: Variant = RELEASE) -> tuple[bytes, dict]:
    code = bytearray(linked["code"])
    if code[:4] != b"SWED":
        raise BuildError("editor image does not start with its header")
    fixup_table = struct.pack(">I", len(linked["fixups"])) + b"".join(
        struct.pack(">I", offset) for offset in linked["fixups"])
    import_table = struct.pack(">I", len(linked["imports"])) + b"".join(
        struct.pack(">I", offset) for offset in linked["imports"])
    code += bytes(-len(code) % 4)
    offsets = {"fixups": len(code)}
    code += fixup_table
    offsets["imports"] = len(code)
    code += import_table
    offsets["hooks"] = len(code)
    code += hook_table
    offsets["hooks_end"] = len(code)
    code += bytes(-len(code) % 4)
    offsets["payload"] = len(code)
    if variant.size is not None:
        if len(code) > variant.size:
            raise BuildError(f"editor image ({len(code)} bytes) exceeds the padded size {variant.size}")
        code += variant.filler(variant.size - len(code))
    struct.pack_into(">I", code, caps["EDH_LENGTH"], len(code))
    struct.pack_into(">I", code, caps["EDH_HOOKS"], offsets["hooks"])
    struct.pack_into(">I", code, caps["EDH_FIXUPS"], offsets["fixups"])
    struct.pack_into(">I", code, caps["EDH_IMPORTS"], offsets["imports"])
    code[caps["EDH_IDENTITY"]:caps["EDH_IDENTITY"] + 8] = bytes.fromhex(SWOS2_RUNTIME_SHA256)[:8]
    struct.pack_into(">I", code, caps["EDH_CODE_LENGTH"], len(code))
    check_cap("editor image", len(code), caps["EDITOR_IMAGE_MAX_SIZE"])
    return bytes(code), offsets


# A model editor base (expansion memory plus the slave area), used to check
# the relocated image; the real base is only known at run time.
MODEL_EDITOR_BASE = 0x40008000


def check_pages(exe: Executable, image: bytes, fixups: list[int], symbols: dict, constants: dict,
                caps: dict) -> dict:
    """Build every extended page exactly as menus_init does, from the image's
    own page_extensions table (relocated to a model base), decode it
    independently and check the native page budget; measure the pages that
    get entries later."""
    base = caps["SWOS2_BASE"]
    moved = relocate_image(image, fixups, MODEL_EDITOR_BASE)
    by_template = {caps[info["symbol"]]: page for page, info in constants["pages"].items()}
    cursor = symbols["page_extensions"]
    results = {}
    while True:
        template_address = struct.unpack_from(">I", moved, cursor)[0]
        if template_address == 0:
            break
        size, crc, work, restore, tail, tail_size = struct.unpack_from(">HIIIIH", moved, cursor + 4)
        (count_patches,) = struct.unpack_from(">H", moved, cursor + 24)
        patches = [struct.unpack_from(">HH", moved, cursor + 26 + 4 * i) for i in range(count_patches)]
        cursor += 26 + 4 * count_patches
        (count_longs,) = struct.unpack_from(">H", moved, cursor)
        longs = [struct.unpack_from(">HI", moved, cursor + 2 + 6 * i) for i in range(count_longs)]
        cursor += 2 + 6 * count_longs
        page = by_template.get(template_address)
        if page is None:
            raise BuildError(f"page_extensions names an unknown template ${template_address:X}")
        info = constants["pages"][page]
        if size != len(info["prefix"]) or crc != crc32(info["prefix"]):
            raise BuildError(f"{page}: size or CRC-32 in page_extensions differs from the measurement")
        start = template_address - base
        prefix = exe.runtime[start:start + size]
        tail_offset = tail - MODEL_EDITOR_BASE
        template = bytearray(prefix) + moved[tail_offset:tail_offset + tail_size]
        if restore:
            struct.pack_into(">I", template, 4, restore)
        for offset, value in patches:
            template[offset] = value & 0xFF
        native_actions = {info["menu"]["entries"][entry]["action_source"] - start: entry
                          for entry in EXTENDED_PAGES[page][3]}
        for offset, value in longs:
            if offset != 0 and offset not in native_actions:
                raise BuildError(f"{page}: a longword patch at {offset} is neither the init "
                                 "callback nor an exported entry action")
            if not MODEL_EDITOR_BASE <= value < MODEL_EDITOR_BASE + len(image):
                raise BuildError(f"{page}: longword patch at {offset} does not point into the editor")
            struct.pack_into(">I", template, offset, value)
        native = EXTENDED_PAGES[page][1]
        menu = decode(bytes(template), 0x40000, 0x40000)
        if len(menu["entries"]) <= native:
            raise BuildError(f"{page}: no entries appended")
        inbound = {target for entry in menu["entries"] for target in entry["navigation"]}
        for index, entry in enumerate(menu["entries"]):
            for neighbour in entry["navigation"]:
                if neighbour != 255 and neighbour >= len(menu["entries"]):
                    raise BuildError(f"{page}: entry {index} navigates to a missing entry")
            if index < native:
                continue
            if MODEL_EDITOR_BASE <= entry["action"] < MODEL_EDITOR_BASE + len(image):
                continue
            # A caption: no action, never selected.
            if entry["action"] or index in inbound or any(n != 255 for n in entry["navigation"]):
                raise BuildError(f"{page}: appended entry {index} has no editor action")
        for offset, entry in native_actions.items():
            if not any(o == offset for o, _ in longs):
                raise BuildError(f"{page}: entry {entry} action exported but not patched")
        expected_restore = restore or info["menu"]["restore"]
        if menu["restore"] != expected_restore:
            raise BuildError(f"{page}: restore callback lost")
        if page == "TEAM_EDITOR":
            check_team_rows(menu, native)
        buffers = count_text_buffers(menu)
        results[page] = {"entries": len(menu["entries"]), "added": len(menu["entries"]) - native,
                         "text_buffers": buffers,
                         "bytes": check_menu_page(page, len(menu["entries"]), buffers, caps)}
    if set(results) != set(constants["pages"]):
        raise BuildError(f"page_extensions covers {sorted(results)}, expected {sorted(constants['pages'])}")
    for page, symbol in MEASURED_PAGES.items():
        menu = decode(exe.runtime, caps[symbol])
        entries, buffers = len(menu["entries"]), count_text_buffers(menu)
        used = check_menu_page(page, entries, buffers, caps)
        results[page] = {"entries": entries, "text_buffers": buffers, "bytes": used,
                         "room_for_entries": (caps["MENU_PAGE_LIMIT"] - used) // caps["MENU_ENTRY_SIZE"]}
    return results


def check_team_rows(menu: dict, native: int) -> None:
    """The team page's row actions: one per player row, on the row's line,
    right of the row's decorations and left of the kits, reached by RIGHT
    from the row's name and leading on to the kit the name led to."""
    entries = menu["entries"]
    kits_x = min(entries[e]["geometry"][0] for e in (5, 6, 7, 9, 10, 11))
    decorations_end = max(e["geometry"][0] + e["geometry"][2] for e in entries[55:58])
    for row, name in enumerate(TEAM_NAME_ROWS):
        action = entries[native + row]
        x, y, w, h = action["geometry"]
        if y != entries[name]["geometry"][1] or h > 10:
            raise BuildError(f"TEAM_EDITOR: row action {row} is not on its row")
        if x < decorations_end or x + w > kits_x:
            raise BuildError(f"TEAM_EDITOR: row action {row} overlaps the decorations or the kits")
        if entries[name]["navigation"][1] != native + row or action["navigation"][0] != name:
            raise BuildError(f"TEAM_EDITOR: row {row} is not linked with its name")


# Own screens: dialog descriptors of the image (dialog.i) and their limits.
DIALOGS = ("database_dialog", "group_dialog", "ok_dialog", "ask_dialog",
           "settings_dialog", "player_dialog", "rules_dialog", "save_dialog", "load_dialog")
def ui_list_size(data: bytes, offset: int, image_length: int, caps: dict, name: str) -> int:
    """Walk a UI command list (ui.i); returns its byte size. Coordinates must
    lie on the band of the screen, opcodes must be known."""
    start = offset
    while True:
        (opcode,) = struct.unpack_from(">H", data, offset)
        offset += 2
        if opcode == caps["UI_END"]:
            return offset - start
        if opcode == caps["UI_RECT"]:   # x,y,w,h,role
            x, y, w, h, _ = struct.unpack_from(">5h", data, offset)
            offset += 10
        elif opcode in (caps["UI_TEXT"], caps["UI_TEXT_AT"]):  # x,y,w,role,align (+string)
            x, y, w, _, _ = struct.unpack_from(">5h", data, offset)
            h = caps["UI_LINE_HEIGHT"]
            offset += 10
            if opcode == caps["UI_TEXT"]:
                end = data.index(b"\0", offset)
                offset = end + 1 + ((end + 1) & 1)
            else:
                offset += 4
        elif opcode in (caps["UI_BUTTON_AT"], caps["UI_ROW_AT"]):  # x,y,w,h,state, label address
            x, y, w, h = struct.unpack_from(">4h", data, offset)
            offset += 14
        else:
            raise BuildError(f"{name}: unknown UI opcode {opcode}")
        if x < caps["DIALOG_BAND_X"] or x + w > caps["DIALOG_BAND_X"] + caps["DIALOG_BAND_WIDTH"] \
                or y < 0 or y + h > caps["UI_SCREEN_ROWS"]:
            raise BuildError(f"{name}: command {opcode} at {x},{y} {w}x{h} leaves the screen band")


def check_dialogs(image: bytes, symbols: dict, caps: dict) -> dict:
    """Assert the size limits of every own screen's descriptor."""
    results = {}
    for name in DIALOGS:
        offset = symbols[name]
        top, height, _role, _title, body, default, cancel, count = struct.unpack_from(">hhhIIhhh", image, offset)
        if count > caps["DIALOG_MAX_BUTTONS"] or count < 0:
            raise BuildError(f"{name}: {count} buttons, at most {caps['DIALOG_MAX_BUTTONS']}")
        if height < caps["DIALOG_MIN_HEIGHT"] or top < 0 or top + height > caps["UI_SCREEN_ROWS"]:
            raise BuildError(f"{name}: band {top}+{height} outside the screen")
        if not -1 <= default < max(count, 1):
            raise BuildError(f"{name}: default button {default} out of range")
        size = caps["DIALOG_BUTTONS"] + count * caps["DIALOG_BUTTON_BYTES"]
        for index in range(count):
            x, y, w, h, _code, _state, _label = struct.unpack_from(
                ">hhhhhhI", image, offset + caps["DIALOG_BUTTONS"] + index * caps["DIALOG_BUTTON_BYTES"])
            if x - 1 < caps["DIALOG_BAND_X"] or x + w + 1 > caps["DIALOG_BAND_X"] + caps["DIALOG_BAND_WIDTH"] \
                    or y - 1 < top + caps["DIALOG_TITLE_ROWS"] + 2 or y + h + 1 > top + height:
                raise BuildError(f"{name}: button {index} at {x},{y} {w}x{h} leaves its band")
        body_size = 0
        if body:
            if not body < len(image):
                raise BuildError(f"{name}: body outside the image")
            body_size = ui_list_size(image, body, len(image), caps, name)
        results[name] = {"buttons": count, "descriptor_bytes": size, "body_bytes": body_size,
                         "band": [top, height]}
    return results


