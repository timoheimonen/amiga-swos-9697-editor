@dataclass(frozen=True)
class Variant:
    """What a build adds to the editor image: sources linked after
    EDITOR_SOURCES, assembler defines for every source, and a fixed image
    size, reached by appending filler(missing) bytes to the composed image.
    The default, RELEASE, is the release build and adds nothing."""
    sources: tuple[Path, ...] = ()
    defines: dict[str, int] = field(default_factory=dict)
    size: int | None = None
    filler: Callable[[int], bytes] = bytes


RELEASE = Variant()


def write_include(path: Path, lines: list[str]) -> None:
    path.write_text("; Generated by tools/build/editor.py. Do not edit.\n" + "\n".join(lines) + "\n")


def string_macro(name: str, text: str) -> list[str]:
    return [f"{name} macro", f"        dc.b    '{text}',0", "        endm"]


