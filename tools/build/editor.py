"""The editor image: the file Editor.bin of the WHDLoad install.

The slave loads the image into the editor area of the expansion memory
(layout.i), checks its length, CRC-32 and identity header, applies its
relocation and import tables, calls editor_init and installs its runtime
hook table.

The image is linked at origin 0 and at FIXUP_PROBE_DELTA (its relocation
table) and once more with every SWOS2 address moved by the same delta (its
import table). It is the linked code followed by the relocation table, the
import table and the runtime hook table. A Variant can add sources and
assembler defines to the image and pad it to a fixed size with a filler;
the release build, the default, does none of this.

Game data never leaves the local build: the editor copies the native pages
at run time after checking the CRC-32 measured here.
"""
from __future__ import annotations

import struct
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from buildlib import (BuildError, Executable, REPO, INCLUDE, assemble, check_cap, check_menu_page,
                      count_text_buffers, crc32, infer_fixups, infer_imports, link, relocate_image,
                      shifted_constants, write_json, FIXUP_PROBE_DELTA, SWOS2_RUNTIME_SHA256, SWOS2_SHA256)
import manifest as patch_manifest
from menu_template import decode

