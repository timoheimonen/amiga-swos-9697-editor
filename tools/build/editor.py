# The image
# ---------------------------------------------------------------------------
def build_image(exe: Executable, caps: dict, out: Path, base_entries: list,
                variant: Variant = RELEASE) -> dict:
    """Link, compose and check the editor image of a variant (by default
    the release build). base_entries are the resolved base patches of the
    slave; a hook may not overlap them."""
    gen = out / "gen"
    shift = out / "gen-shifted"
    gen.mkdir(parents=True, exist_ok=True)
    shift.mkdir(exist_ok=True)
    constants = editor_constants(exe, caps, gen)
    (shift / "swos2.i").write_text(shifted_constants(INCLUDE / "swos2.i", caps, caps["SWOS2_BASE"],
                                                     caps["SWOS2_IMAGE_END"]))
    linked = link_editor(out, gen, shift, caps, variant)
    symbols = {**linked["map"].symbols, **{k: v for k, v in caps.items() if k.startswith("WORK_")}}
    patches = patch_manifest.load_manifest(DATA / "manifest.json")
    if any(patch.table != "runtime" for patch in patches):
        raise BuildError("the editor manifest may only hold runtime hooks")
    runtime = patch_manifest.resolve(patches, exe, images={"editor": symbols},
                                     image_bytes={"editor": linked["code"]}, base=caps["SWOS2_BASE"])
    hook_table = patch_manifest.table_bytes(runtime)
    patch_manifest.decode_table(hook_table)
    patch_manifest.check_disjoint(base_entries, runtime)
    image, offsets = compose_image(linked, hook_table, caps, variant)
    pages = check_pages(exe, image, linked["fixups"], linked["map"].symbols, constants, caps)
    dialogs = check_dialogs(image, linked["map"].symbols, caps)
    (out / "runtime_table.bin").write_bytes(hook_table)
    (out / "runtime_table.i").write_text(patch_manifest.table_include(runtime, "runtime"))
    write_json(out / "image_symbols.json", {k: v for k, v in sorted(linked["map"].symbols.items())})
    return {"image": image, "offsets": offsets, "fixups": linked["fixups"], "imports": linked["imports"],
            "symbols": linked["map"].symbols, "runtime": runtime, "pages": pages, "dialogs": dialogs}

