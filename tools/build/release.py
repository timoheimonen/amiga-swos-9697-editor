"""The release files inside patch.py.

patch.py carries the release build's SWOS.slave, SWOS.info and Editor.bin
as base64 text with their SHA-256 between its "GENERATED BY build.py"
markers, so that installing needs only Python. build_release builds the
files, embed rewrites that section with them and embedded reads it back,
for example to compare it with a fresh release build.
"""
from __future__ import annotations

import base64
import hashlib
import re
from pathlib import Path

from buildlib import REPO, BuildError, Executable

PATCH = REPO / "patch.py"
BEGIN = "# BEGIN GENERATED BY build.py - do not edit by hand\n"
END = "# END GENERATED BY build.py\n"
ORDER = ("SWOS.slave", "SWOS.info", "Editor.bin")
LINE = 76


def section(files: dict[str, bytes]) -> str:
    """The generated section for the release files (in ORDER)."""
    lines = [BEGIN, "BLOBS: dict[str, tuple[str, ...]] = {\n"]
    for name in ORDER:
        text = base64.b64encode(files[name]).decode("ascii")
        lines.append(f'    "{name}": (\n')
        lines += [f'        "{text[i:i + LINE]}",\n' for i in range(0, len(text), LINE)]
        lines.append("    ),\n")
    lines.append("}\n")
    lines.append("BLOB_SHA256: dict[str, str] = {\n")
    lines += [f'    "{name}": "{hashlib.sha256(files[name]).hexdigest()}",\n' for name in ORDER]
    lines.append("}\n")
    lines.append(END)
    return "".join(lines)


def split(text: str) -> tuple[str, str, str]:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise BuildError("patch.py has no GENERATED BY build.py section")
    return text[:start], text[start:end + len(END)], text[end + len(END):]


def embed(files: dict[str, bytes], patch: Path = PATCH) -> bool:
    """Writes the release files into patch.py; True when it changed."""
    head, current, tail = split(patch.read_text())
    new = section(files)
    if new == current:
        return False
    patch.write_text(head + new + tail)
    return True


def embedded(patch: Path = PATCH) -> dict[str, bytes]:
    """The files patch.py carries now, each checked against its SHA-256."""
    _, current, _ = split(patch.read_text())
    blobs = dict(re.findall(r'^    "([^"]+)": \(\n((?:        "[^"]*",\n)*)    \),\n', current, re.M))
    digests = dict(re.findall(r'^    "([^"]+)": "([0-9a-f]{64})",\n', current, re.M))
    files = {}
    for name, body in blobs.items():
        data = base64.b64decode("".join(re.findall(r'"([^"]*)"', body)))
        if hashlib.sha256(data).hexdigest() != digests.get(name):
            raise BuildError(f"patch.py: the embedded {name} does not match its SHA-256")
        files[name] = data
    return files


def base_entries(exe: Executable, caps: dict) -> list:
    """The slave's base patches resolved with a placeholder slave: the
    editor's hooks may not overlap them."""
    import manifest as patch_manifest
    from slave_build import DATA
    patches = patch_manifest.load_manifest(DATA / "base_manifest.json")
    placeholder = {name: 0 for patch in patches for kind, name in patch.replacement.items()
                   if kind in patch_manifest.IMAGE_KINDS}
    return patch_manifest.resolve(patches, exe, images={"slave": placeholder},
                                  image_bytes={"slave": bytes(0x1000)}, base=caps["SWOS2_BASE"])


def build_release(exe: Executable, caps: dict, out: Path) -> tuple[dict[str, bytes], dict, dict]:
    """The release files (ORDER) built into out: the release editor image,
    the slave that checks it, the icon. Returns the files, the editor build
    and the slave build."""
    import editor as editor_image
    from slave_build import build_slave
    out.mkdir(parents=True, exist_ok=True)
    editor = editor_image.build_image(exe, caps, out, base_entries(exe, caps))
    slave = build_slave(exe, caps, out, editor["image"])
    slave_name, icon_name, editor_name, _ = slave["names"]
    files = {slave_name: slave["slave"], icon_name: slave["icon"], editor_name: editor["image"]}
    for name, data in files.items():
        (out / name).write_bytes(data)
    return files, editor, slave

