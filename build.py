"""Assemble the WHDLoad slave and the editors and embed them in patch.py.

Usage: python3 build.py "Disk 1.adf" [--vasm PATH] [--vlink PATH]

Requires the vasm 68000 assembler with Motorola syntax (vasmm68k_mot) and the
vlink linker. The build reads the game's executable SWOS2 from your own disk
1 image (identified by its SHA-256) to check every place where the editors
change the game (the length and the SHA-256 of the bytes expected there, as
the patch manifests in tools/build/ record them) and the game's menus that
the editors copy at run time; no byte of the game enters the built files.
Only the section of patch.py between the "GENERATED BY build.py" markers is
written again, so users of patch.py need only Python 3.

The editors are src/editor/ (resident/ and editors/, the shared definitions
in include/), the slave is whdload/src/slave.s with its services; both are
linked position independent and every size and menu page budget is checked.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools" / "build"))

import buildlib  # noqa: E402
import release  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("disk1", type=Path, help="the image of the game's disk 1")
    parser.add_argument("--vasm", default="vasmm68k_mot", help="the vasm assembler (vasmm68k_mot)")
    parser.add_argument("--vlink", default="vlink", help="the vlink linker")
    args = parser.parse_args(argv)
    buildlib.VASM, buildlib.VLINK = args.vasm, args.vlink
    try:
        with tempfile.TemporaryDirectory(prefix="swos-build-") as name:
            work = Path(name)
            buildlib.WORK_BUILD = work
            exe = buildlib.extract_executable(buildlib.load_disk1(args.disk1))
            caps = buildlib.layout_constants(buildlib.clean_dir(work / "constants"))
            files, editor, _ = release.build_release(exe, caps, work / "release")
            changed = release.embed(files, ROOT / "patch.py")
    except buildlib.BuildError as exc:
        print(f"build failed: {exc}", file=sys.stderr)
        return 1
    for file_name, data in files.items():
        print(f"{file_name}: {len(data)} bytes, SHA-256 {hashlib.sha256(data).hexdigest()}")
    print(f"editor code: {editor['offsets']['fixups']} bytes; menu pages: "
          + ", ".join(f"{page} {info['bytes']}" for page, info in editor["pages"].items()))
    print("patch.py " + ("updated" if changed else "unchanged"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
