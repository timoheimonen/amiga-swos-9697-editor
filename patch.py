def report_main(args) -> int:
    paths: list[Path] = []
    for path in args.saves:
        if path.is_dir():
            install = Install(path)
            found = [install.data / n for n in install.names() if Path(n).suffix.upper() in competition_report.KINDS]
            if not found:
                raise UserError(f"{install.data}: no .DIY, .PRE or .SEA save")
            paths += found
        else:
            paths.append(path)
    competitions = []
    for path in paths:
        try:
            competitions += competition_report.read_save(path.name, path.read_bytes())
        except ValueError as exc:
            raise UserError(str(exc)) from None
    files = {name: content.encode("latin-1") for name, content in competition_report.report_files(competitions).items()}
    publish(args.output, files, new_root=True)
    print(f"Created {args.output.resolve()}: {len(competitions)} competitions from {len(paths)} saves")
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else list(argv)
    if argv and argv[0] not in COMMANDS and not argv[0].startswith("-"):
        argv = ["install", *argv]
    args = parser().parse_args(argv)
    handlers = {"install": install_main, "list": list_main, "check": check_main, "export": export_main,
                "import": import_main, "db": db_main, "report": report_main, "results": results_main,
                "machine": machine_main}
    try:
        return handlers[args.command](args)
    except (UserError, ValueError, KeyError, OSError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
