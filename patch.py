def check_bytes(name: str, raw: bytes, install: Install | None = None) -> tuple[bool, str]:
    """(accepted, line) for one file as the game or the editors check it."""
    upper = name.upper()
    if upper.endswith(".TAC"):
        code, details = tactic_data.check_record(raw)
        if code != tactic_data.TC_OK:
            return False, "FILE DAMAGED: " + tactic_data.problem_text(code, details)
        return True, f"tactic {tactic_name(raw)}: the editor accepts it"
    if upper.endswith(".DEF"):
        lines = definition_data.problem_lines(raw)
        if lines:
            return False, "FILE DAMAGED: " + " ".join(lines)
        document = definition_data.decode(raw)
        return True, (f"{document['family']} {document['name']!r}, {document['teams']} teams, "
                      f"CRC-32 {definition_crc(raw)}: the editor accepts it")
    if upper in (custom_set.CUSTOM_SET_NAME, custom_set.BACKUP_NAME):
        problems = customs_problems(raw, install)
        if problems:
            return False, "; ".join(problems[:5])
        return True, f"custom set, {len(raw) // database_set.TEAM_SIZE} teams, CRC-32 {custom_set.set_fingerprint(raw)}"
    if upper in (database_set.MANIFEST_NAME, database_set.BACKUP_NAME):
        code, detail = database_set.check_manifest(raw)
        if code != database_set.MC_OK:
            return False, "DATABASE NOT FOUND: " + database_set.problem_text(code, detail)
        manifest = database_set.decode_manifest(raw)
        return True, (f"database set {database_label(manifest.label)} {database_set.manifest_crc(raw):08X}, "
                      f"generation {manifest.generation}, {plural(len(manifest.entries), 'file')}")
    if upper[-4:] in (".DLD", ".DLP", ".DLS", ".DLC"):
        code, detail = database_set.check_link(raw)
        if code != database_set.MC_OK:
            return False, database_set.problem_text(code, detail)
        link = database_set.decode_link(raw)
        m = link["manifest"]
        return True, f"link of a {link['save_suffix']} save to {database_label(m['label'])} {m['crc32']}"
    if upper == match_log.LOG_NAME:
        records, problems = match_log.scan_log(raw)
        text = f"match log, {len(records)} matches"
        if problems:
            return False, text + "; " + "; ".join(p.text() for p in problems[:5])
        return True, text
    if upper == match_log.MACHINE_NAME:
        try:
            machine, identity = match_log.read_machine(raw)
        except ValueError as exc:
            return False, str(exc)
        return True, f"machine {machine}, install identity {identity:08X}"
    if upper[-4:] in COMPETITION_KINDS:
        try:
            competition_data.decode(raw, kind=COMPETITION_KINDS[upper[-4:]])
        except (ValueError, KeyError) as exc:
            return False, f"not a readable save: {exc}"
        return True, f"{upper[-3:]} save, {len(raw)} bytes"
    return False, "not a file of the game or the editors"


def tactic_name(raw: bytes) -> str:
    return raw[:tactic_data.NAME_SIZE].split(b"\0", 1)[0].decode("latin-1")


def definition_crc(raw: bytes) -> str:
    return f"{definition_data.crc32(raw[definition_data.HEADER_SIZE:]):08X}"


def customs_problems(raw: bytes, install: Install | None) -> list[str]:
    """The reasons the team editor would refuse a custom set's teams."""
    try:
        teams = database_set.group_teams(raw)
    except ValueError as exc:
        return [str(exc).upper()]
    if install is None:
        return []
    original = install.original_customs()
    if len(raw) != len(original):
        return [f"THE CUSTOM SET HAS {len(teams)} TEAMS, THE GAME'S HAS {len(original) // database_set.TEAM_SIZE}"]
    problems = []
    current = install.data / custom_set.CUSTOM_SET_NAME
    previous = current.read_bytes() if current.is_file() else original
    if len(previous) != len(original):
        previous = original
    for ordinal, (team, base) in enumerate(zip(teams, database_set.group_teams(previous))):
        result = custom_set.team_validate(team, base)
        if result is not None:
            reason, slot = result
            where = f" PLAYER {slot + 1}" if slot >= 0 else ""
            problems.append(f"CUSTOM TEAM {ordinal + 1}{where}: {reason}")
    return problems


def check_main(args) -> int:
    install = Install(args.install) if args.install else None
    failed = 0
    for path in args.files:
        accepted, line = check_bytes(path.name, path.read_bytes(), install)
        print(f"{path.name}: {line}")
        failed += not accepted
    return 1 if failed else 0


