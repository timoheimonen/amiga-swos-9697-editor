def inventory(install: Install) -> dict:
    names = install.names()
    data = install.data
    result: dict = {"install": str(install.root), "version": VERSION, "files": len(names),
                    "files_max": NAMES_MAX,
                    "game_saves": sum(n.upper().endswith(GAME_SAVE_SUFFIXES) for n in names),
                    "game_saves_max": GAME_SAVES_MAX}
    editor = install.root / EDITOR_NAME
    if not editor.is_file():
        result["editor"] = "missing: the original game runs"
    elif EDITOR_NAME in BLOB_SHA256 and sha256(editor.read_bytes()) == BLOB_SHA256[EDITOR_NAME]:
        result["editor"] = f"V{VERSION}"
    else:
        result["editor"] = "another build"
    machine = data / match_log.MACHINE_NAME
    if machine.is_file():
        try:
            name, identity = match_log.read_machine(machine.read_bytes())
            result["machine"] = {"name": name, "identity": f"{identity:08X}"}
        except ValueError as exc:
            result["machine"] = {"problem": str(exc)}
    else:
        result["machine"] = None
    customs = data / custom_set.CUSTOM_SET_NAME
    if customs.is_file():
        raw = customs.read_bytes()
        entry = {"file": customs.name, "teams": len(raw) // database_set.TEAM_SIZE,
                 "fingerprint": custom_set.set_fingerprint(raw),
                 "backup": (data / custom_set.BACKUP_NAME).is_file()}
        problems = customs_problems(raw, None)
        if problems:
            entry["problem"] = problems[0]
        result["custom_set"] = entry
    else:
        result["custom_set"] = None
    result["database"] = database_inventory(install, names)
    result["tactics"] = []
    result["definitions"] = []
    result["saves"] = []
    used: set[str] = set()
    links = {}
    for name in names:
        upper = name.upper()
        if upper[-4:] in (".DLD", ".DLP", ".DLS", ".DLC"):
            links[upper] = name
    declared = {e.name for e in (result["database"] or {}).get("_entries", [])}
    for name in names:
        upper = name.upper()
        raw = None
        if upper.endswith(".TAC"):
            raw = (data / name).read_bytes()
            accepted, line = check_bytes(name, raw)
            entry = {"file": name, "name": tactic_name(raw) if accepted else None}
            if not accepted:
                entry["problem"] = line
            result["tactics"].append(entry)
            used.add(name)
        elif upper.endswith(".DEF"):
            raw = (data / name).read_bytes()
            lines = definition_data.problem_lines(raw)
            if lines:
                entry = {"file": name, "problem": "FILE DAMAGED: " + " ".join(lines)}
            else:
                document = definition_data.decode(raw)
                db = document["database"]
                entry = {
                    "file": name, "name": document["name"], "family": document["family"],
                    "teams": document["teams"], "fingerprint": definition_crc(raw),
                    "database": "original" if db["kind"] == "original" else
                    f"{database_label(db['label'])} {db['crc32']}",
                    "tactics": sum(1 for t in document.get("tactics", []) if t is not None)}
            backup = next((n for n in names if n.upper() == upper + ".BAK"), None)
            entry["backup"] = backup is not None
            result["definitions"].append(entry)
            used.add(name)
            if backup is not None:
                used.add(backup)
        elif upper[-4:] in COMPETITION_KINDS or upper.endswith(".HIL"):
            entry = {"file": name, "bytes": (data / name).stat().st_size}
            if upper[-4:] in COMPETITION_KINDS:
                link = links.get(database_set.link_name(upper))
                entry["database"] = "original"
                if link is not None:
                    used.add(link)
                    raw_link = (data / link).read_bytes()
                    save = (data / name).read_bytes()
                    code, detail = database_set.check_link(raw_link, database_set.family_of_save(upper), save)
                    if code != database_set.MC_OK:
                        entry["database"] = "link damaged: " + database_set.problem_text(code, detail)
                    else:
                        m = database_set.decode_link(raw_link)["manifest"]
                        entry["database"] = f"{database_label(m['label'])} {m['crc32']}"
            result["saves"].append(entry)
            used.add(name)
    log = data / match_log.LOG_NAME
    if log.is_file():
        records, problems = match_log.scan_log(log.read_bytes())
        result["match_log"] = {"matches": len(records), "problems": [p.text() for p in problems]}
    else:
        result["match_log"] = None
    known = {custom_set.CUSTOM_SET_NAME, custom_set.BACKUP_NAME, database_set.MANIFEST_NAME,
             database_set.BACKUP_NAME, database_set.SWITCH_NAME, match_log.LOG_NAME, match_log.MACHINE_NAME}
    generations = [n for n in names if database_set.parse_generation_name(n) is not None]
    if result["database"] is not None:
        result["database"]["old_generations"] = sum(1 for n in generations if n not in declared)
        result["database"].pop("_entries", None)
    result["other"] = [n for n in names if n not in used and n not in known and n not in generations
                       and n.upper() not in links]
    return result


def database_inventory(install: Install, names: list[str]) -> dict | None:
    if database_set.MANIFEST_NAME not in names:
        return None
    raw = (install.data / database_set.MANIFEST_NAME).read_bytes()
    entry: dict = {"in_use": database_set.read_switch(install.data)}
    code, detail = database_set.check_manifest(raw)
    if code != database_set.MC_OK:
        entry["problem"] = "DATABASE NOT FOUND: " + database_set.problem_text(code, detail)
        return entry
    manifest = database_set.decode_manifest(raw)
    entry.update({"label": manifest.label, "fingerprint": f"{database_set.manifest_crc(raw):08X}",
                  "generation": manifest.generation, "files": len(manifest.entries),
                  "groups": [e.group for e in manifest.entries if e.group in database_set.SUPPORTED_GROUPS],
                  "copies": [COPY_NAMES[e.group] for e in manifest.entries if e.group in COPY_NAMES],
                  "_entries": manifest.entries})
    for item in manifest.entries:
        path = install.data / item.name
        code, name = database_set.check_group_file(item, path.read_bytes() if path.is_file() else None)
        if code != database_set.MC_OK:
            entry["problem"] = "DATABASE NOT FOUND: " + database_set.problem_text(code, name)
            break
    return entry


