def db_main(args) -> int:
    install = Install(args.install)
    data = install.data
    if args.db == "check":
        manifest, raw = database_set.read_set(data)
        if manifest is None:
            print("original database: no edited set in", data)
            return 0
        base = install.base()
        for entry in manifest.entries:
            path = database_set.stored(data, entry.name)
            code, name = database_set.check_group_file(entry, path.read_bytes() if path.is_file() else None)
            if code != database_set.MC_OK:
                raise UserError("DATABASE NOT FOUND: " + database_set.problem_text(code, name))
        groups, copies = database_set.set_contents(data, base.groups)
        problems = []
        pool = database_set.original_pool(base.groups)
        for entry in manifest.entries:
            if entry.group in database_set.SUPPORTED_GROUPS:
                # the set's own values are the ones the editors loaded and keep
                problems += database_set.validate_group(entry.group, groups[entry.group], base.groups[entry.group],
                                                        pool, groups[entry.group])
        problems += database_set.check_copies(copies, groups)
        try:
            database_set.check_cup_lists(database_set.cup_lists_of(copies, base), groups)
        except database_set.CupError as exc:
            problems.append(str(exc))
        if problems:
            raise UserError("\n".join(problems))
        print(f"the editors accept this set: {database_label(manifest.label)} {database_set.manifest_crc(raw):08X}, "
              f"generation {manifest.generation}, {plural(len(manifest.entries), 'file')}, "
              f"USE EDITED DATABASE {'on' if database_set.read_switch(data) else 'off'}")
        return 0
    if args.db == "switch":
        on = args.state == "on"
        if on:
            manifest, _ = database_set.read_set(data)
            if manifest is None:
                raise UserError("there is no edited set to use")
            for entry in manifest.entries:       # as the editor's switch verifies the set
                path = database_set.stored(data, entry.name)
                code, name = database_set.check_group_file(entry, path.read_bytes() if path.is_file() else None)
                if code != database_set.MC_OK:
                    raise UserError("DATABASE NOT FOUND: " + database_set.problem_text(code, name))
        admit(install, [database_set.SWITCH_NAME])
        database_set.write_switch(data, on)
        print(f"USE EDITED DATABASE {args.state}")
        return 0
    base = install.base()
    labels = install.labels()
    groups, copies = database_set.set_contents(data, base.groups)
    current, _ = database_set.read_set(data)
    if args.db == "export":
        files = {}
        for group in database_set.SUPPORTED_GROUPS:
            files[f"TEAM.{group:03d}.json"] = json_bytes(team_data.decode(groups[group]))
        players, teams = database_set.export_csv(groups, labels)
        files["players.csv"] = players.encode("latin-1")
        files["teams.csv"] = teams.encode("latin-1")
        files["cups.csv"] = database_set.export_cups_csv(database_set.cup_lists_of(copies, base), groups).encode("latin-1")
        publish(args.output, files, new_root=True)
        print(f"Created {args.output.resolve()} with {len(files)} files")
        return 0
    if args.db == "diff":
        label = args.label if args.label is not None else (current.label if current else "")
        text = database_set.pack_text(database_set.diff(base.groups, groups, label,
                                                        lists=database_set.cup_lists_of(copies, base), base=base))
        publish(args.pack.parent, {args.pack.name: text.encode("ascii")}, new_root=False)
        print(f"Created {args.pack.resolve()}")
        return 0
    if args.db == "import":
        groups, lists, pack_label = database_set.read_sources(list(args.files), base, labels, groups,
                                                              database_set.cup_lists_of(copies, base))
        label = args.label if args.label is not None else (
            pack_label if pack_label is not None else (current.label if current else ""))
    else:  # apply
        try:
            pack = json.loads(args.pack.read_text())
        except (OSError, ValueError) as exc:
            raise UserError(f"{args.pack.name}: not readable JSON ({exc})") from None
        groups, label = database_set.apply(pack, base.groups)
        if args.label is not None:
            label = args.label
        lists = database_set.pack_cups(pack, groups)
    plan = database_set.plan_set(data, base.groups, groups, label, base=base, lists=lists)
    if plan.manifest is None:
        print("unchanged: the set already holds these values")
        return 0
    admit(install, list(plan.files) + [database_set.MANIFEST_NAME, database_set.BACKUP_NAME])
    database_set.write_plan(data, plan)
    raw = database_set.stored(data, database_set.MANIFEST_NAME).read_bytes()
    print(f"wrote generation {plan.manifest.generation}: {database_label(plan.manifest.label)} "
          f"{database_set.manifest_crc(raw):08X}; USE EDITED DATABASE "
          f"{'on' if database_set.read_switch(data) else 'off'}")
    return 0


