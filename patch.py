def json_bytes(document) -> bytes:
    return (json.dumps(document, indent=1, ensure_ascii=True) + "\n").encode("ascii")


def export_files(install: Install) -> dict[str, bytes]:
    """The JSON (and CSV) files of export by relative path."""
    files: dict[str, bytes] = {}
    data = install.data
    names = install.names()
    upper_names = {n.upper() for n in names}
    if custom_set.CUSTOM_SET_NAME in upper_names:
        raw = custom_set.stored(data, custom_set.CUSTOM_SET_NAME).read_bytes()
        files[f"{custom_set.CUSTOM_SET_NAME}.json"] = json_bytes(team_data.decode(raw))
        players, teams = database_set.export_customs_csv(raw, install.labels())
        files[CUSTOMS_CSV[0]] = players.encode("latin-1")
        files[CUSTOMS_CSV[1]] = teams.encode("latin-1")
    for name in names:
        upper = name.upper()
        path = data / name
        if upper.endswith(".TAC"):
            raw = path.read_bytes()
            if tactic_data.check_record(raw)[0] == tactic_data.TC_OK:
                files[f"tactics/{name}.json"] = json_bytes(tactic_data.decode(raw))
        elif upper.endswith(".DEF"):
            raw = path.read_bytes()
            if not definition_data.problem_lines(raw):
                files[f"definitions/{name}.json"] = json_bytes(definition_data.decode(raw))
        elif upper[-4:] in COMPETITION_KINDS:
            try:
                document = competition_data.decode(path.read_bytes(), kind=COMPETITION_KINDS[upper[-4:]])
            except (ValueError, KeyError):
                continue
            files[f"saves/{name}.json"] = json_bytes({"read_only": True, **document})
        elif upper[-4:] in (".DLD", ".DLP", ".DLS", ".DLC"):
            try:
                files[f"saves/{name}.json"] = json_bytes({"read_only": True,
                                                          **database_set.decode_link(path.read_bytes())})
            except ValueError:
                continue
    manifest, raw_manifest = (database_set.read_set(data) if database_set.MANIFEST_NAME in upper_names
                              else (None, None))
    if manifest is not None:
        files[f"database/{database_set.MANIFEST_NAME}.json"] = json_bytes(
            {"read_only": True, **database_set.manifest_document(raw_manifest)})
        for entry in manifest.entries:
            path = database_set.stored(data, entry.name)
            if not path.is_file():
                continue
            raw = path.read_bytes()
            if entry.group in database_set.SUPPORTED_GROUPS:
                files[f"database/TEAM.{entry.group:03d}.json"] = json_bytes(team_data.decode(raw))
    return files


def export_main(args) -> int:
    install = Install(args.install)
    files = export_files(install)
    if not files:
        raise UserError(f"{install.data}: nothing to export")
    publish(args.output, files, new_root=True)
    print(f"Created {args.output.resolve()} with {len(files)} files")
    return 0


def import_plan(install: Install, paths: list[Path], replace: bool = False):
    """(writes, notes, set plan): the files import writes into the save
    directory by name, lines about what stays unchanged, and the new
    version of the edited database (or None). Every file is checked as
    the editors check it."""
    writes: dict[str, bytes] = {}
    notes: list[str] = []
    groups_sources: list[Path] = []
    customs: bytes | None = None
    customs_csv: dict[str, str] = {}
    for path in paths:
        name = path.name
        upper = name.upper()
        if upper.endswith(".JSON"):
            target = name[:-5]
            target_upper = target.upper()
            try:
                document = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                raise UserError(f"{name}: not readable JSON ({exc})") from None
            if isinstance(document, dict) and document.get("read_only"):
                raise UserError(f"{name}: an export of a game save, a link or a manifest is for reading only")
            if target_upper == custom_set.CUSTOM_SET_NAME:
                customs = encode_document(name, team_data.encode, document)
            elif target_upper.endswith(".TAC"):
                raw = encode_document(name, tactic_data.encode, document)
                code, details = tactic_data.check_record(raw)
                if code != tactic_data.TC_OK:
                    raise UserError(f"{name}: {tactic_data.problem_text(code, details)}")
                writes[target_upper] = raw
            elif target_upper.endswith(".DEF"):
                raw = encode_document(name, definition_data.encode, document)
                lines = definition_data.problem_lines(raw)
                if lines:
                    raise UserError(f"{name}: " + " ".join(lines))
                writes[target_upper] = raw
            elif target_upper.startswith("TEAM.") and target_upper[5:].isdigit():
                groups_sources.append(path)
            else:
                raise UserError(f"{name}: expected CUSTOMS.EDT.json, NAME.TAC.json, NAME.DEF.json or TEAM.ggg.json")
        elif name.lower() in CUSTOMS_CSV:
            customs_csv[name.lower()] = path.read_text(encoding="latin-1")
        elif upper.endswith((".TAC", ".DEF")):
            raw = path.read_bytes()
            accepted, line = check_bytes(name, raw)
            if not accepted:
                raise UserError(f"{name}: {line}")
            writes[upper] = raw
        else:
            raise UserError(f"{name}: import takes the JSON and CSV files of export, .TAC and .DEF files")
    for target in list(writes):
        if not safe_name(target):
            raise UserError(f"{target}: a name in {SAVE_DIRECTORY}/ has 1-{NAME_LENGTH_MAX} characters with a dot")
        existing = install.data / target
        if existing.is_file():
            if existing.read_bytes() == writes[target]:
                notes.append(f"{target}: unchanged")
                del writes[target]
            elif not replace:
                raise UserError(f"{target} exists in {SAVE_DIRECTORY}/ with other contents (--replace replaces it)")
    if customs_csv:
        base = customs if customs is not None else current_customs(install)
        try:
            result = database_set.import_csv({database_set.CUSTOM_GROUP: base},
                                             {database_set.CUSTOM_GROUP: current_customs(install)}, install.labels(),
                                             customs_csv.get(CUSTOMS_CSV[0]), customs_csv.get(CUSTOMS_CSV[1]),
                                             CUSTOMS_CSV[0], CUSTOMS_CSV[1])
        except ValueError as exc:
            raise UserError(str(exc)) from None
        customs = result[database_set.CUSTOM_GROUP]
    if customs is not None:
        problems = customs_problems(customs, install)
        if problems:
            raise UserError("CUSTOMS.EDT: " + "; ".join(problems[:5]))
        if customs == current_customs(install) and custom_set.stored(install.data, custom_set.CUSTOM_SET_NAME).is_file():
            notes.append("CUSTOMS.EDT: unchanged")
        else:
            writes[custom_set.CUSTOM_SET_NAME] = customs
    set_plan = None
    if groups_sources:
        base = install.base()
        groups, copies = database_set.set_contents(install.data, base.groups)
        groups, lists, pack_label = database_set.read_sources(
            groups_sources, base, install.labels(), groups, database_set.cup_lists_of(copies, base))
        current, _ = database_set.read_set(install.data)
        set_plan = database_set.plan_set(install.data, base.groups, groups,
                                         current.label if current else "", base=base, lists=lists)
        if set_plan.manifest is None:
            notes.append("database: unchanged")
    return writes, notes, set_plan


def current_customs(install: Install) -> bytes:
    path = custom_set.stored(install.data, custom_set.CUSTOM_SET_NAME)
    return path.read_bytes() if path.is_file() else install.original_customs()


def encode_document(name: str, encoder, document) -> bytes:
    try:
        return encoder(document)
    except (ValueError, KeyError, TypeError, IndexError, struct.error) as exc:
        raise UserError(f"{name}: {exc}") from None


def definition_backups(install: Install, writes: dict[str, bytes]) -> dict[str, bytes]:
    """NAME.DEF.BAK for every definition import replaces, as SAVE DEFINITION
    keeps it: the previous file when it is a sound definition."""
    backups = {}
    for name in writes:
        existing = install.data / name
        backup = name + ".BAK"
        if name.endswith(".DEF") and existing.is_file() and safe_name(backup):
            previous = existing.read_bytes()
            if not definition_data.problem_lines(previous):
                backups[backup] = previous
    return backups


def import_main(args) -> int:
    install = Install(args.install)
    writes, notes, set_plan = import_plan(install, args.files, args.replace)
    backups = definition_backups(install, writes)
    new_names = [n for n in writes if n != custom_set.CUSTOM_SET_NAME] + list(backups)
    if custom_set.CUSTOM_SET_NAME in writes:
        new_names += [custom_set.CUSTOM_SET_NAME, custom_set.BACKUP_NAME]
    if set_plan is not None and set_plan.manifest is not None:
        new_names += list(set_plan.files) + [database_set.MANIFEST_NAME, database_set.BACKUP_NAME]
    admit(install, new_names)
    for note in notes:
        print(note)
    for name, raw in writes.items():
        if name == custom_set.CUSTOM_SET_NAME:
            previous = custom_set.stored(install.data, name).is_file()
            try:
                kept = custom_set.save_custom_set(install.data, raw, whole=len(install.original_customs()))
            except custom_set.SaveError as exc:
                raise UserError(f"CUSTOMS.EDT: {exc}") from None
            print(f"CUSTOMS.EDT: written ({custom_set.set_fingerprint(raw)})"
                  + (", the previous one kept as CUSTOMS.BAK" if kept else
                     ", the previous one was not a whole set: CUSTOMS.BAK unchanged" if previous else ""))
        else:
            backup = name + ".BAK"
            if backup in backups:
                write_verified(install.data / backup, backups[backup])
            write_verified(install.data / name, raw)
            print(f"{name}: written" + (f", the previous one kept as {backup}" if backup in backups else ""))
    if set_plan is not None and set_plan.manifest is not None:
        database_set.write_plan(install.data, set_plan)
        raw = database_set.stored(install.data, database_set.MANIFEST_NAME).read_bytes()
        print(f"database: generation {set_plan.manifest.generation} written "
              f"({database_label(set_plan.manifest.label)} {database_set.manifest_crc(raw):08X})")
    return 0


