def verified_disks(paths: list[Path]) -> dict[int, bytes]:
    """The user's two disk images by number, each checked by its SHA-256."""
    images: dict[int, bytes] = {}
    known = {value: number for number, value in DISK_SHA256.items()}
    for path in paths:
        data = Path(path).read_bytes()
        number = known.get(sha256(data))
        if number is None:
            size = "" if len(data) == DISK_SIZE else f" ({len(data)} bytes, a disk image has {DISK_SIZE})"
            raise UserError(f"{path}: not a disk of the supported SWOS 96-97 release{size}. Needed: disk 1 "
                            f"[a2] (SHA-256 {DISK_SHA256[1][:16]}...) and disk 2 (SHA-256 {DISK_SHA256[2][:16]}...)")
        if number in images:
            raise UserError(f"{path}: disk {number} was given twice")
        images[number] = data
    if sorted(images) != [1, 2]:
        raise UserError("give the images of both disks")
    return images


def safe_name(name: str) -> bool:
    """A file name the save directory admits: 1-29 characters with a dot, no path."""
    return (1 <= len(name) <= NAME_LENGTH_MAX and "." in name and "/" not in name and ":" not in name
            and "\\" not in name and name not in (".", "..") and all(32 < ord(c) < 127 for c in name))


def game_save(name: str) -> bool:
    """A save the game lists (and counts among its 45): named as the game
    names its saves, a base of 1-8 characters and then, at the first dot,
    .DIY .PRE .SEA .CAR .TAC or .HIL in capitals. The game's chooser copies
    a chosen name into 13-byte buffers without a bound, so the slave never
    lists a longer name."""
    base, dot, suffix = name.partition(".")
    return bool(dot) and 1 <= len(base) <= GAME_SAVE_BASE_MAX and "." + suffix in GAME_SAVE_SUFFIXES


