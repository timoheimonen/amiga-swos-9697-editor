def json_bytes(document) -> bytes:
    return (json.dumps(document, indent=1, ensure_ascii=True) + "\n").encode("ascii")


def export_files(install: Install, delimiter: str = ",") -> dict[str, bytes]:
    """The JSON (and CSV) files of export by relative path. The custom
    teams are always there: without a CUSTOMS.EDT they are the game's own,
    the ones EDIT CUSTOM TEAMS starts from."""
    files: dict[str, bytes] = {}
    data = install.data
    names = install.names()
    upper_names = {n.upper() for n in names}
    raw = current_customs(install)
    files[f"{custom_set.CUSTOM_SET_NAME}.json"] = json_bytes(team_data.decode(raw))
    players, teams = database_set.export_customs_csv(raw, install.labels(), delimiter)
    files[CUSTOMS_CSV[0]] = players.encode("latin-1")
    files[CUSTOMS_CSV[1]] = teams.encode("latin-1")
    for name in names:
        upper = name.upper()
        path = data / name
        if upper == tactic_data.KEPT_NAME:
            try:
                files[f"{tactic_data.KEPT_NAME}.json"] = json_bytes(tactic_data.decode_kept(path.read_bytes()))
            except ValueError:
                continue
        elif upper.endswith(".TAC"):
            raw = path.read_bytes()
            if tactic_data.check_record(raw)[0] == tactic_data.TC_OK:
                files[f"tactics/{name}.json"] = json_bytes(tactic_data.decode(raw))
        elif upper.endswith(".DEF"):
            raw = path.read_bytes()
            if not definition_data.problem_lines(raw):
                files[f"definitions/{name}.json"] = json_bytes(definition_data.decode(raw))
        elif upper[-4:] in COMPETITION_KINDS:
            try:
                document = competition_data.decode(path.read_bytes(), kind=COMPETITION_KINDS[upper[-4:]])
            except (ValueError, KeyError):
                continue
            files[f"saves/{name}.json"] = json_bytes({"read_only": True, **document})
        elif upper[-4:] in (".DLD", ".DLP", ".DLS", ".DLC"):
            try:
                files[f"saves/{name}.json"] = json_bytes({"read_only": True,
                                                          **database_set.decode_link(path.read_bytes())})
            except ValueError:
                continue
    manifest, raw_manifest = (database_set.read_set(data) if database_set.MANIFEST_NAME in upper_names
                              else (None, None))
    if manifest is not None:
        files[f"database/{database_set.MANIFEST_NAME}.json"] = json_bytes(
            {"read_only": True, **database_set.manifest_document(raw_manifest)})
        for entry in manifest.entries:
            path = database_set.stored(data, entry.name)
            if not path.is_file():
                continue
            raw = path.read_bytes()
            if entry.group in database_set.SUPPORTED_GROUPS:
                files[f"database/TEAM.{entry.group:03d}.json"] = json_bytes(team_data.decode(raw))
    return files


