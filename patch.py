class UserError(ValueError):
    """A refusal with a message for the user; nothing has been written."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def embedded(name: str) -> bytes:
    """One of the release files build.py embedded, checked against its SHA-256."""
    if name not in BLOBS:
        raise UserError("this patch.py holds no built editor; build it first")
    data = base64.b64decode("".join(BLOBS[name]))
    if sha256(data) != BLOB_SHA256[name]:
        raise UserError(f"the embedded file {name} is damaged")
    return data


