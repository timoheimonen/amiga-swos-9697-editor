def game_save_kind(name: str) -> bool:
    """A name with a game save's suffix in any case, listed by the game or not."""
    return name.upper().endswith(GAME_SAVE_SUFFIXES)


class Install:
    """An install directory written by install (or its save directory)."""

    def __init__(self, path: Path):
        path = Path(path)
        if path.name == SAVE_DIRECTORY and (path.parent / DISK_NAMES[0]).is_file():
            path = path.parent
        if not (path / DISK_NAMES[0]).is_file() or not (path / DISK_NAMES[1]).is_file():
            raise UserError(f"{path}: not an install directory (Disk.1 and Disk.2 are missing)")
        self.root = path
        self.data = path / SAVE_DIRECTORY
        if not self.data.is_dir():
            raise UserError(f"{path}: the save directory {SAVE_DIRECTORY}/ is missing")
        self._disks: dict[int, bytes] | None = None
        self._base = None
        self._labels = None

    def disks(self) -> dict[int, bytes]:
        if self._disks is None:
            self._disks = verified_disks([self.root / DISK_NAMES[0], self.root / DISK_NAMES[1]])
        return self._disks

    def base(self) -> database_set.Base:
        if self._base is None:
            disks = self.disks()
            self._base = database_set.base_from_disks(disks[1], disks[2])
        return self._base

    def labels(self) -> list[str]:
        if self._labels is None:
            self._labels = database_set.nationality_labels_from_disk1(self.disks()[1])
        return self._labels

    def original_customs(self) -> bytes:
        return database_set.custom_group_from_disk2(self.disks()[2])

    def names(self) -> list[str]:
        return sorted(p.name for p in self.data.iterdir() if p.is_file())


def publish(root: Path, files: dict[str, bytes], *, new_root: bool) -> list[Path]:
    """Create every file (never replace one) and read it back. On a failure
    only the files and directories this call created are removed."""
    for name in files:
        parts = Path(name).parts
        if not parts or Path(name).is_absolute() or any(p in ("", ".", "..") for p in parts) or len(parts) > 2:
            raise UserError("invalid output file name: " + name)
    if new_root:
        if root.exists() or root.is_symlink():
            raise UserError(f"the output must be a new directory: {root}")
    elif root.is_symlink() or not root.is_dir():
        raise UserError(f"not a directory: {root}")
    created_files: list[Path] = []
    created_dirs: list[Path] = []
    try:
        if new_root:
            root.mkdir(parents=True)
            created_dirs.append(root)
        for name, data in files.items():
            path = root / name
            if not path.parent.exists():
                path.parent.mkdir()
                created_dirs.append(path.parent)
            with path.open("xb") as stream:
                created_files.append(path)
                stream.write(data)
            if path.read_bytes() != data:
                raise OSError("the file reads back differently: " + name)
    except BaseException:
        for path in reversed(created_files):
            path.unlink(missing_ok=True)
        for path in reversed(created_dirs):
            try:
                path.rmdir()
            except OSError:
                pass
        raise
    return created_files


def write_verified(path: Path, data: bytes) -> None:
    if not data:
        raise UserError(f"{path.name}: a file is never written empty")
    path.write_bytes(data)
    if path.read_bytes() != data:
        raise OSError(f"{path.name}: the file reads back differently")


def admit(install: Install, new_names: list[str]) -> None:
    """The save directory's rules for names that do not exist yet."""
    existing = set(install.names())
    known = {name.upper() for name in existing}
    fresh = [name for name in dict.fromkeys(new_names) if name.upper() not in known]
    for name in fresh:
        if not safe_name(name):
            raise UserError(f"{name}: a name in {SAVE_DIRECTORY}/ has 1-{NAME_LENGTH_MAX} characters with a dot")
    if len(existing) + len(fresh) > NAMES_MAX:
        raise UserError(f"{SAVE_DIRECTORY}/ would hold more than {NAMES_MAX} files")
    for name in fresh:
        if game_save_kind(name) and not game_save(name):
            raise UserError(f"{name}: the game lists a tactic or save only by a name of 1-{GAME_SAVE_BASE_MAX} "
                            "characters before its suffix, in capitals")
    saves = [n for n in existing if game_save(n)]
    new_saves = [n for n in fresh if game_save(n)]
    if new_saves and len(saves) + len(new_saves) > GAME_SAVES_MAX:
        raise UserError(f"{SAVE_DIRECTORY}/ would hold more than {GAME_SAVES_MAX} game saves "
                        "(.DIY .PRE .SEA .CAR .TAC .HIL), the most the game lists")


