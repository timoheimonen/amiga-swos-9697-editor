def log_paths(paths: list[Path]) -> list[Path]:
    """MATCHES.LOG files, given directly or as install or save directories."""
    result = []
    for path in paths:
        if path.is_dir():
            for candidate in (path / SAVE_DIRECTORY / match_log.LOG_NAME, path / match_log.LOG_NAME):
                if candidate.is_file():
                    result.append(candidate)
                    break
            else:
                raise UserError(f"{path}: no {match_log.LOG_NAME}")
        else:
            result.append(path)
    return result


def results_main(args) -> int:
    chosen = match_log.selection(args.definition, args.teams, args.family, args.machine, args.sequence, args.points)
    result = match_log.results([match_log.read_log(path) for path in log_paths(args.logs)], chosen)
    files = {name: text.encode("latin-1") for name, text in match_log.result_files(result).items()}
    publish(args.output, files, new_root=True)
    print(f"Created {args.output.resolve()}: {len(result.matches)} matches")
    for line in result.warnings:
        print(f"warning: {line}")
    return 0


def machine_main(args) -> int:
    install = Install(args.install)
    path = install.data / match_log.MACHINE_NAME
    identity = None
    if path.is_file():
        try:
            identity = match_log.read_machine(path.read_bytes())[1]
        except ValueError:
            identity = None
    identity = match_log.new_install() if identity is None else identity
    try:
        raw = match_log.machine_file(args.name, identity)
    except ValueError as exc:
        raise UserError(str(exc)) from None
    admit(install, [match_log.MACHINE_NAME])
    write_verified(path, raw)
    print(f"machine {args.name.upper()}, install identity {identity:08X}")
    return 0


