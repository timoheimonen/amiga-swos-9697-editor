def prepare_install(images: dict[int, bytes], machine: str = match_log.DEFAULT_MACHINE,
                    sources: list[Path] | None = None, label: str | None = None,
                    identity: int | None = None) -> tuple[dict[str, bytes], dict]:
    """The files of a new install by relative path, and what it holds."""
    files = {SLAVE_NAME: embedded(SLAVE_NAME), ICON_NAME: embedded(ICON_NAME), EDITOR_NAME: embedded(EDITOR_NAME),
             DISK_NAMES[0]: images[1], DISK_NAMES[1]: images[2]}
    identity = match_log.new_install() if identity is None else identity
    try:
        files[f"{SAVE_DIRECTORY}/{match_log.MACHINE_NAME}"] = match_log.machine_file(machine, identity)
    except ValueError as exc:
        raise UserError(f"--machine: {exc}") from None
    summary = {"machine": machine.upper(), "identity": f"{identity:08X}", "set": None}
    if sources:
        base = database_set.base_from_disks(images[1], images[2])
        labels = database_set.nationality_labels_from_disk1(images[1])
        groups, lists, pack_label = database_set.read_sources(
            list(sources), base, labels, dict(base.groups), database_set.cup_lists_of({}, base))
        name = label if label is not None else (pack_label or "")
        plan = database_set.plan_set(Path("/nonexistent-save-directory"), base.groups, groups, name,
                                     base=base, lists=lists)
        if plan.manifest is None:
            raise UserError("the given files change nothing: every group equals the original database")
        for file_name, raw in plan.files.items():
            files[f"{SAVE_DIRECTORY}/{file_name}"] = raw
        files[f"{SAVE_DIRECTORY}/{database_set.MANIFEST_NAME}"] = plan.raw_manifest
        files[f"{SAVE_DIRECTORY}/{database_set.SWITCH_NAME}"] = database_set.encode_switch(True)
        summary["set"] = {"label": plan.manifest.label, "generation": plan.manifest.generation,
                          "fingerprint": f"{database_set.manifest_crc(plan.raw_manifest):08X}",
                          "files": len(plan.files)}
    return files, summary


