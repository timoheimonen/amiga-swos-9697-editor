DRY_RUN_END = "dry run: nothing was written"
CHANGES_SHOWN = 40


def shown(value) -> str:
    if isinstance(value, list):
        return " ".join(str(item) for item in value)
    return "-" if value is None else str(value)


def team_changes(before: bytes, after: bytes, group: int | None = None,
                 labels: list[str] | None = None) -> list[str]:
    """One line per team whose record differs between two versions of a
    group or of the custom set, with every field that changes as old ->
    new (a nationality by its label, given the labels); at most
    CHANGES_SHOWN lines, then the number of the teams left out."""
    def value(name: str, item) -> str:
        return labels[item] if name == "nationality" and labels and item < len(labels) else shown(item)
    lines = []
    where = "  " if group is None else f"  group {group} "
    old_teams, new_teams = database_set.group_teams(before), database_set.group_teams(after)
    for ordinal, (old, new) in enumerate(zip(old_teams, new_teams)):
        if old == new:
            continue
        a, b = database_set.team_fields(old), database_set.team_fields(new)
        parts = [name.replace("_", " ") if name == "name" else
                 f"{name.replace('_', ' ')} {shown(a[name])} -> {shown(b[name])}"
                 for name in database_set.TEAM_FIELDS if a[name] != b[name]]
        for slot in range(16):
            start = database_set.PLAYERS + slot * database_set.PLAYER_SIZE
            pa = database_set.player_fields(old[start:start + database_set.PLAYER_SIZE])
            pb = database_set.player_fields(new[start:start + database_set.PLAYER_SIZE])
            fields = [f"{name} {value(name, pa[name])} -> {value(name, pb[name])}"
                      for name in database_set.PLAYER_FIELDS if pa[name] != pb[name]]
            if fields:
                parts.append(f"player {slot + 1} {pb['name']} ({', '.join(fields)})")
        title = b["name"] if a["name"] == b["name"] else f"{a['name']} -> {b['name']}"
        lines.append(f"{where}team {ordinal} {title}: " + ("; ".join(parts) or "other bytes"))
    if len(old_teams) != len(new_teams):
        lines.append(f"{where}{len(old_teams)} -> {len(new_teams)} teams")
    if len(lines) > CHANGES_SHOWN:
        lines[CHANGES_SHOWN:] = [f"{where}and {plural(len(lines) - CHANGES_SHOWN, 'more team')}"]
    return lines


def returning_lines(install: Install, plan) -> list[str]:
    """The groups and cups the set in the save directory changes and the
    new version does not: they are the original database's again."""
    previous, _ = database_set.read_set(install.data)
    if previous is None or plan.manifest is None:
        return []
    kept = {entry.group for entry in plan.manifest.entries}
    lines = []
    for entry in previous.entries:
        if entry.group in kept:
            continue
        if entry.group in database_set.SUPPORTED_GROUPS:
            lines.append(f"  group {entry.group}: the original database's again (the edits in {entry.name} "
                         "are not part of the new version; the file stays)")
        elif entry.group in database_set.CUP_NAMES:
            lines.append(f"  {database_set.CUP_NAMES[entry.group]}: the original participants again")
    return lines


def set_plan_lines(install: Install, plan) -> list[str]:
    """What a new version of the edited database would write, against the
    set in the save directory now (the original groups without one)."""
    current, _ = database_set.set_contents(install.data, install.base().groups)
    previous, _ = database_set.read_set(install.data)
    lines = [f"database: generation {plan.manifest.generation} would be written "
             f"({database_label(plan.manifest.label)} {database_set.data_fingerprint(plan.raw_manifest):08X}), "
             + (plural(len(plan.files), "new file") if plan.files else "no new group file")]
    if previous is not None and previous.label != plan.manifest.label:
        lines.append(f"  label {database_label(previous.label)} -> {database_label(plan.manifest.label)}")
    for name, raw in plan.files.items():
        group, _ = database_set.parse_generation_name(name)
        if group in database_set.SUPPORTED_GROUPS:
            lines.append(f"  {name}: group {group}")
            lines += team_changes(current[group], raw, group, install.labels())
        else:
            lines.append(f"  {name}: a copy that follows the set (a cup's teams or the transfer pool)")
    return lines + returning_lines(install, plan)


def set_notes(install: Install) -> list[str]:
    """What the user should know about a new version of the set: that it
    is not in use yet."""
    if database_set.read_switch(install.data):
        return []
    return [f"  USE EDITED DATABASE is off: patch.py db switch {install.root} on (or the switch in "
            "EDIT DATABASE) takes the set into use"]


